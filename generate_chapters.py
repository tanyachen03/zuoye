def generate_chapter_html(chapter_data):
    cid = chapter_data["id"]
    title = chapter_data["title"]
    sections = chapter_data["sections"]
    key_point = chapter_data["key_point"]
    tip_box = chapter_data["tip_box"]
    warn_box = chapter_data["warn_box"]
    
    # 上一章/下一章链接
    prev_chapter = f"chapter{cid-1}.html" if cid > 1 else None
    next_chapter = f"chapter{cid+1}.html" if cid < 24 else None
    
    # 侧边栏章节列表（从course_chapters获取）
    sidebar_items = chapter_data["course_chapters"]
    
    # 构建侧边栏
    sidebar_html = ""
    for (ch_id, ch_title) in sidebar_items:
        active_class = "active" if ch_id == cid else ""
        sidebar_html += f'<li><a href="chapter{ch_id}.html" class="{active_class}"><span class="chapter-number">{ch_id:02d}</span> {ch_title}</a></li>\n'
    
    # 构建章节内容
    sections_html = ""
